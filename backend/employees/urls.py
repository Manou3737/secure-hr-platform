from rest_framework.routers import DefaultRouter
from django.urls import path
from .views import (
    EmployeeProfileViewSet,
    DepartmentViewSet,
    SiteViewSet,
    PositionViewSet,
    LeaveRequestViewSet,
    BankAccountViewSet,
    PerformanceReviewViewSet,
    HRDocumentViewSet,
    OnboardingJourneyViewSet,
    OnboardingTaskViewSet,
    DocumentAccessLogViewSet,
    DashboardView,
)

router = DefaultRouter()
router.register(
    "departments",
    DepartmentViewSet,
    basename="department",
)
router.register(
    "sites",
    SiteViewSet,
    basename="site",
)
router.register(
    "positions",
    PositionViewSet,
    basename="position",
)
router.register(
    "bank-accounts",
    BankAccountViewSet,
    basename="bank-account",
)
router.register(
    "performance-reviews",
     PerformanceReviewViewSet,
     basename="performance-review"
)
router.register(
    "hr-documents",
    HRDocumentViewSet,
    basename="hr-document",
)
router.register(
    "leave-requests",
    LeaveRequestViewSet,
    basename="leave-request",
)
router.register(
    "document-access-logs",
    DocumentAccessLogViewSet,
    basename="document-access-log",
)
router.register(
    "",
    EmployeeProfileViewSet,
    basename="employee",
)
router.register(
    "onboarding/journeys",
    OnboardingJourneyViewSet,
    basename="onboarding-journey",
)
router.register(
    "onboarding/tasks",
    OnboardingTaskViewSet,
    basename="onboarding-task",
)
urlpatterns = [
    path(
        "dashboard/",
        DashboardView.as_view(),
        name="dashboard",
    ),
] + router.urls
